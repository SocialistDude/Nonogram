import 'dart:io';
import 'package:nonogram_tools/manifest.dart';
import 'package:nonogram_tools/png_reader.dart';
import 'package:nonogram_tools/solver.dart';

const String _projectRoot = '..';
const String _levelsDir = '$_projectRoot/assets/levels';
const String _pendingDir = '$_projectRoot/assets/levels_pending';
const String _manifestPath = '$_levelsDir/manifest.json';
const String _outPath = '$_projectRoot/lib/domain/levels/builtin_levels.dart';

void main(List<String> args) {
  if (args.contains('-h') || args.contains('--help')) {
    stdout.writeln(_help);
    return;
  }

  final levelsDir = Directory(_levelsDir);
  final pendingDir = Directory(_pendingDir);
  final manifestFile = File(_manifestPath);

  // ── 1. Загружаем манифест ─────────────────────────────────
  LevelManifest manifest = LevelManifest.load(manifestFile);

  // Если манифеста нет, а levels/ уже содержит PNG — засеваем
  // его в алфавитном порядке (одноразовая миграция).
  if (manifest.entries.isEmpty && levelsDir.existsSync()) {
    final existing = levelsDir
        .listSync()
        .whereType<File>()
        .where((f) => f.path.toLowerCase().endsWith('.png'))
        .toList()
      ..sort((a, b) => a.path.compareTo(b.path));

    if (existing.isNotEmpty) {
      stdout.writeln('📄 Манифест не найден — засеваю из ${_levelsDir}/:');
      for (final f in existing) {
        final name = f.uri.pathSegments.last;
        final lv = readLevelPng(f);
        manifest.entries.add(LevelEntry(
          file: name,
          width: lv.width,
          height: lv.height,
        ));
      }
    }
  }

  // ── 2. Проверяем целостность манифеста ────────────────────
  for (final e in manifest.entries) {
    final f = File('$_levelsDir/${e.file}');
    if (!f.existsSync()) {
      stderr.writeln(
        '❌ Манифест ссылается на ${e.file}, но файла нет в $_levelsDir/.\n'
            '   Восстанови файл или отредактируй $_manifestPath вручную.',
      );
      exit(2);
    }
  }

  // ── 3. Читаем pending ─────────────────────────────────────
  if (!pendingDir.existsSync()) {
    stdout.writeln('ℹ️  Папки $_pendingDir/ нет — новых уровней не будет.');
    _finish(levelsDir, manifest, manifestFile);
    return;
  }

  final pending = pendingDir
      .listSync()
      .whereType<File>()
      .where((f) => f.path.toLowerCase().endsWith('.png'))
      .toList()
    ..sort((a, b) => a.path.compareTo(b.path));

  if (pending.isEmpty) {
    stdout.writeln('ℹ️  В $_pendingDir/ нет PNG — новых уровней не будет.');
    _finish(levelsDir, manifest, manifestFile);
    return;
  }

  stdout.writeln('🔍 Проверяю ${pending.length} новых уровней...\n');

  // ── 4. Проверяем ВСЁ до любых изменений на диске ──────────
  final existingNames = manifest.entries.map((e) => e.file).toSet();
  final accepted = <({File file, String name, int width, int height})>[];

  for (final f in pending) {
    final name = f.uri.pathSegments.last;

    if (existingNames.contains(name)) {
      stderr.writeln('❌ $name уже есть в $_levelsDir/. '
          'Переименуй или удали из pending.');
      exit(1);
    }

    try {
      final lv = readLevelPng(f);
      final s = countSolutions(lv.width, lv.height, lv.rowClues, lv.colClues);

      switch (s) {
        case 1:
          stdout.writeln(
            '  ✅ $name  ${lv.width}×${lv.height}',
          );
          accepted.add((file: f, name: name, width: lv.width, height: lv.height));
          break;
        case 0:
          stderr.writeln('  ❌ $name — нет решения');
          exit(1);
        case 2:
          stderr.writeln('  ⚠️  $name — решений ≥ 2 (неоднозначный)');
          exit(1);
        default:
          stderr.writeln('  ❓ $name — прервано (maxStates/timeout)');
          exit(1);
      }
    } catch (e) {
      stderr.writeln('  ❌ $name — $e');
      exit(1);
    }
  }

  // ── 5. Транзакция: двигаем файлы, обновляем манифест ──────
  stdout.writeln('\n📦 Переношу в $_levelsDir/:');
  for (final a in accepted) {
    final dest = File('$_levelsDir/${a.name}');
    a.file.renameSync(dest.path);
    manifest.entries.add(LevelEntry(file: a.name, width: a.width, height: a.height));
    stdout.writeln('   → ${a.name}');
  }

  manifest.save(manifestFile);
  _finish(levelsDir, manifest, manifestFile);
}

void _finish(
    Directory levelsDir,
    LevelManifest manifest,
    File manifestFile,
    ) {
  _writeBuiltin(levelsDir, manifest, File(_outPath));
  stdout.writeln(
    '\n✅ Готово. Уровней в игре: ${manifest.entries.length}.\n'
        '   Манифест: $_manifestPath\n'
        '   Код:      $_outPath',
  );
}

void _writeBuiltin(
    Directory levelsDir,
    LevelManifest manifest,
    File outFile,
    ) {
  final buf = StringBuffer();
  buf.writeln('// GENERATED FILE — DO NOT EDIT MANUALLY.');
  buf.writeln('// Generated by: cd tool && dart run bin/generate.dart');
  buf.writeln('// Source: assets/levels/*.png (order in manifest.json)');
  buf.writeln();
  buf.writeln("import '../game_level.dart';");
  buf.writeln();
  buf.writeln('final List<GameLevel> builtinLevels = [');

  for (int i = 0; i < manifest.entries.length; i++) {
    final entry = manifest.entries[i];
    final file = File('${levelsDir.path}/${entry.file}');
    final lv = readLevelPng(file);
    buf.writeln('  _build(${i + 1}, ${lv.width}, ${lv.height}, [');
    for (final row in lv.solutionGrid) {
      buf.writeln("    '${row.map((b) => b ? '1' : '0').join()}',");
    }
    buf.writeln('  ]),');
  }

  buf.writeln('];');
  buf.writeln();
  buf.writeln(_helpers);

  outFile.parent.createSync(recursive: true);
  outFile.writeAsStringSync(buf.toString());
}

const String _help = '''
Usage: dart run bin/generate.dart

Читает PNG из assets/levels_pending/, проверяет каждый на единственное
решение, переносит валидные в assets/levels/ и перегенерирует
lib/domain/levels/builtin_levels.dart.

Порядок уровней хранится в assets/levels/manifest.json и НИКОГДА не
меняется сам по себе — новые уровни добавляются в конец.

Имена файлов: произвольные, но должны заканчиваться на _<N>x<N>.png.
Примеры: car_16x16.png, level_apple_5x5.png, красивая_машина_16x16.png
''';

// _helpers — вставь сюда ту же строку, что была в generate.dart
const String _helpers = r'''
GameLevel _build(int levelNumber, int width, int height, List<String> rows) {
  final grid = rows
      .map((r) => r.split('').map((c) => c == '1').toList(growable: false))
      .toList(growable: false);
  return GameLevel(
    levelNumber: levelNumber,
    width: width,
    height: height,
    solutionGrid: grid,
    rowClues: _rowClues(grid, width, height),
    colClues: _colClues(grid, width, height),
  );
}

List<List<int>> _rowClues(List<List<bool>> grid, int width, int height) {
  final out = <List<int>>[];
  for (int r = 0; r < height; r++) {
    final clue = <int>[];
    int count = 0;
    for (int c = 0; c < width; c++) {
      if (grid[r][c]) {
        count++;
      } else if (count > 0) {
        clue.add(count);
        count = 0;
      }
    }
    if (count > 0) clue.add(count);
    out.add(clue.isEmpty ? [0] : clue);
  }
  return out;
}

List<List<int>> _colClues(List<List<bool>> grid, int width, int height) {
  final out = <List<int>>[];
  for (int c = 0; c < width; c++) {
    final clue = <int>[];
    int count = 0;
    for (int r = 0; r < height; r++) {
      if (grid[r][c]) {
        count++;
      } else if (count > 0) {
        clue.add(count);
        count = 0;
      }
    }
    if (count > 0) clue.add(count);
    out.add(clue.isEmpty ? [0] : clue);
  }
  return out;
}
''';